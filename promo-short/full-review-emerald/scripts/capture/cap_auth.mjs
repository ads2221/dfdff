import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const OUT = 'v2/desk';
const b = await chromium.launch();
const mk = async st => { const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1.5, ...(st ? { storageState: st } : {}) });
  await ctx.addInitScript(() => { try { localStorage.setItem('ui_theme', 'emerald'); } catch (e) {} }); return ctx.newPage(); };
const p = await mk(null);
await p.goto('https://jupiter-dca-bot.online/panel/auth', { waitUntil: 'commit', timeout: 90000 }).catch(() => {});
await p.waitForTimeout(8000); console.log('url', p.url());
await p.screenshot({ path: `${OUT}/auth_login.png` });
fs.writeFileSync(`${OUT}/auth.txt`, await p.evaluate(() => document.body.innerText));
const reg = p.getByText(/^(Регистрация|Создать аккаунт|Зарегистрироваться)$/i).first();
await reg.click({ timeout: 4000 }).catch(e => console.log('noreg'));
await p.waitForTimeout(2000);
await p.screenshot({ path: `${OUT}/auth_register.png` });
const boxes = await p.evaluate(() => [...document.querySelectorAll('input,button,form')].map(e => { const r = e.getBoundingClientRect(); return [e.tagName, (e.placeholder || e.innerText || '').slice(0, 30), Math.round(r.x), Math.round(r.y), Math.round(r.width), Math.round(r.height)]; }).filter(a => a[4] > 0));
console.log(JSON.stringify(boxes));
const q = await mk('state.json');
await q.goto('https://jupiter-dca-bot.online/panel/docs', { waitUntil: 'commit', timeout: 90000 }).catch(() => {});
await q.waitForTimeout(9000);
await q.screenshot({ path: `${OUT}/docs_pview.png` });
const hh = await q.evaluate(() => { const m = document.querySelector('main'); return [...m.querySelectorAll('*')].filter(e => ['sticky', 'fixed'].includes(getComputedStyle(e).position)).map(e => { const r = e.getBoundingClientRect(); return [e.tagName, Math.round(r.x), Math.round(r.y), Math.round(r.width), Math.round(r.height)]; }); });
console.log('sticky', JSON.stringify(hh));
const ifr = await q.evaluate(() => { const f = document.querySelector('iframe'); if (!f) return null; const r = f.getBoundingClientRect(); return [r.x, r.y, r.width, r.height]; });
console.log('iframe', JSON.stringify(ifr));
await b.close();
